"""
Offline training pipeline for FraudScope.

Loads a PUBLIC/SYNTHETIC fraud dataset (never real bank data), trains a
gradient-boosted classifier with explicit class-imbalance handling, fits a
SHAP TreeExplainer as a sanity check, and saves a versioned model artifact
plus metadata.

Run: python -m src.train
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import shap
from sklearn.model_selection import train_test_split
from xgboost import XGBClassifier

from src.config import FEATURE_COLUMNS, TARGET_COLUMN, settings
from src.features import to_feature_matrix
from src.synthetic_data import generate_synthetic_creditcard_data

logging.basicConfig(level=settings.log_level, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger("fraudscope.train")


def _file_hash(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            h.update(chunk)
    return h.hexdigest()[:16]


def load_dataset() -> tuple[pd.DataFrame, str, bool]:
    """Load the dataset from disk, or generate a synthetic-for-demo fallback.

    Returns (dataframe, dataset_source_label, is_synthetic).

    A sidecar marker file (`<data_path>.synthetic_marker`) records whether
    the CSV at data_path was generated by this repo's synthetic generator,
    so re-running training against an already-generated stand-in file
    still labels it honestly instead of assuming anything found on disk
    must be the real public dataset.
    """
    data_path = settings.data_path
    marker_path = f"{data_path}.synthetic_marker"

    if os.path.exists(data_path):
        if os.path.exists(marker_path):
            logger.warning(
                "[synthetic-for-demo] Loading previously-generated SYNTHETIC "
                "stand-in dataset from %s (marker file present).",
                data_path,
            )
            df = pd.read_csv(data_path)
            return df, "synthetic-for-demo (locally generated stand-in)", True

        logger.info("Loading dataset from %s", data_path)
        df = pd.read_csv(data_path)
        source_label = "public-kaggle-creditcard-fraud-detection (or user-provided CSV)"
        return df, source_label, False

    logger.warning(
        "[synthetic-for-demo] %s not found -- generating a SYNTHETIC stand-in "
        "dataset with matching schema. This is NOT the real Kaggle dataset and "
        "NOT real bank/customer data.",
        data_path,
    )
    Path(data_path).parent.mkdir(parents=True, exist_ok=True)
    df = generate_synthetic_creditcard_data(random_state=settings.random_state)
    df.to_csv(data_path, index=False)
    Path(marker_path).write_text(
        "This file marks data/creditcard.csv as a locally-generated "
        "synthetic-for-demo stand-in, NOT the real Kaggle dataset and NOT "
        "real bank/customer data. Delete this marker (and the CSV) and "
        "supply a real dataset to train on real public data instead.\n"
    )
    return df, "synthetic-for-demo (locally generated stand-in)", True


def train() -> dict:
    df, dataset_source, is_synthetic = load_dataset()

    X = to_feature_matrix(df)
    y = df[TARGET_COLUMN].to_numpy(dtype=int)

    logger.info("Dataset rows=%d, fraud=%d (%.4f%%)", len(df), y.sum(), 100 * y.mean())

    # Stratified split is critical: with ~0.17% positive rate, a naive
    # random split can easily produce a test set with almost no fraud rows.
    X_train, X_test, y_train, y_test = train_test_split(
        X, y,
        test_size=settings.test_size,
        stratify=y,
        random_state=settings.random_state,
    )

    # Class imbalance handling: scale_pos_weight tells XGBoost to weight
    # the minority (fraud) class proportionally to how rare it is, rather
    # than letting the model collapse to "always predict legit" and still
    # score ~99.8% raw accuracy. This is the real, defensible technical
    # talking point for this project: accuracy alone is meaningless here.
    n_pos = y_train.sum()
    n_neg = len(y_train) - n_pos
    scale_pos_weight = (n_neg / n_pos) if n_pos > 0 else 1.0
    logger.info("scale_pos_weight=%.2f (n_neg=%d, n_pos=%d)", scale_pos_weight, n_neg, n_pos)

    model = XGBClassifier(
        n_estimators=300,
        max_depth=4,
        learning_rate=0.08,
        subsample=0.9,
        colsample_bytree=0.9,
        scale_pos_weight=scale_pos_weight,
        eval_metric="aucpr",
        random_state=settings.random_state,
        n_jobs=-1,
    )
    model.fit(X_train, y_train)

    # Fail fast if SHAP can't explain this model -- explainability is a
    # hard requirement of the service, not a nice-to-have.
    logger.info("Fitting SHAP TreeExplainer as a sanity check...")
    explainer = shap.TreeExplainer(model)
    sample = X_test[: min(5, len(X_test))]
    shap_values = explainer.shap_values(sample)
    assert shap_values.shape[0] == len(sample), "SHAP explainer output shape mismatch"
    logger.info("SHAP TreeExplainer OK on sample shape=%s", shap_values.shape)

    Path(settings.model_path).parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, settings.model_path)
    logger.info("Saved model artifact to %s", settings.model_path)

    dataset_hash = _file_hash(settings.data_path) if os.path.exists(settings.data_path) else None
    metadata = {
        "model_version": settings.model_version,
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "algorithm": "XGBClassifier (gradient-boosted trees)",
        "dataset_source": dataset_source,
        "dataset_is_synthetic": is_synthetic,
        "dataset_path": settings.data_path,
        "dataset_hash_sha256_16": dataset_hash,
        "n_rows": int(len(df)),
        "n_fraud": int(y.sum()),
        "fraud_rate": float(y.mean()),
        "feature_columns": FEATURE_COLUMNS,
        "scale_pos_weight": float(scale_pos_weight),
        "test_size": settings.test_size,
        "random_state": settings.random_state,
        "honesty_note": (
            "This model is trained on a public or synthetic-for-demo dataset. "
            "It is not trained on, and has never seen, real bank or customer "
            "transaction data."
        ),
    }
    with open(settings.model_metadata_path, "w") as f:
        json.dump(metadata, f, indent=2)
    logger.info("Saved metadata to %s", settings.model_metadata_path)

    # Persist the split indices' worth of test data for evaluate.py so
    # evaluation runs against the exact same held-out set used here.
    np.savez(
        Path(settings.model_path).parent / "test_split.npz",
        X_test=X_test, y_test=y_test,
    )

    return metadata


if __name__ == "__main__":
    meta = train()
    print(json.dumps(meta, indent=2))
